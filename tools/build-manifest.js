#!/usr/bin/env node
// Regenerates js/data/manifest.js (the list of element data files the app and
// the geometry editor load) and the matching js/data/* entries in sw.js's
// PRECACHE. Run after adding / renaming / deleting a file in js/data/:
//     node tools/build-manifest.js
// (the GitHub Action .github/workflows/manifest.yml does it on every push).
// Safe to run repeatedly: it writes nothing when nothing changed.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const dataDir = path.join(root, 'js', 'data');

const files = fs.readdirSync(dataDir)
  .filter(f => f.endsWith('.js') && f !== 'manifest.js')
  .map(f => f.slice(0, -3))
  .sort();

const manifest =
`// GENERATED by tools/build-manifest.js — do not edit by hand.
// Lists every element data file in js/data/. Loaded as a classic (blocking)
// script so the data files below are in place before any deferred app script
// runs; the path is derived from this script's own URL, so the same file
// works for index.html and geometry-editor/index.html, over http and file://.
(function(){
  var base = document.currentScript.src.replace(/manifest\\.js[^\\/]*$/, '');
  ${JSON.stringify(files)}.forEach(function(f){
    document.write('<script src="' + base + f + '.js"><\\/script>');
  });
})();
`;
function write(p, text){
  if (fs.existsSync(p) && fs.readFileSync(p, 'utf8') === text) return false;
  fs.writeFileSync(p, text); return true;
}
let changed = write(path.join(dataDir, 'manifest.js'), manifest);

// sw.js precache: replace the js/data/* block, keep everything else.
const swPath = path.join(root, 'sw.js');
let sw = fs.readFileSync(swPath, 'utf8');
const lines = sw.split('\n').filter(l => !/^\s*"js\/data\//.test(l));
const entries = ['manifest', ...files].map(f => `  "js/data/${f}.js",`);
const at = lines.findIndex(l => /^\s*"js\/elements\//.test(l));
if (at < 0) throw new Error('sw.js: no js/elements/ entry to anchor on');
lines.splice(at, 0, ...entries);
changed = write(swPath, lines.join('\n')) || changed;
console.log(changed ? 'updated' : 'up to date', '—', files.length, 'data files');
